test('an employee tracks time with a timer and by hand', async ({ employeePage: page }) => {
  await open(page, 'home', 'Home')
  await page.getByRole('button', { name: 'Timer', exact: true }).click()
  const box = dialog(page, 'Track time')
  await box.getByRole('combobox', { name: /^Project/ }).fill('cold')
  await page.getByRole('option', { name: /Cold store expansion/ }).click()
  await box.getByRole('button', { name: 'Start timer' }).click()
  const stop = page.getByRole('button', { name: /^Stop: .*Cold store expansion/ })
  await stop.click()
  await expect(stop).toBeHidden()
  await page.getByRole('button', { name: /^Edit .*Cold store/ }).click()
  await dialog(page, 'Edit entry').getByLabel('Hours').fill('2.25')
  await dialog(page, 'Edit entry').getByRole('button', { name: 'Save entry' }).click()
  await expect(page.locator('.entry-time')).toHaveText('2.25')
  await page.getByRole('button', { name: 'Week', exact: true }).click()
  const cell = page.getByRole('textbox', { name: /Cold store expansion, Friday/ }).first()
  await cell.fill('3.5')
  await cell.press('Enter')
  await expect(page.locator('.week-grid tfoot td').nth(7)).toHaveText('3.50')
  await page.getByRole('button', { name: 'Submit week for approval' }).click()
  await dialog(page).getByRole('button', { name: 'Submit week' }).click()
  await expect(page.getByText('Waiting for approval')).toBeVisible()
  await page.getByRole('button', { name: 'Take back' }).click()
  await expect(page.getByRole('button', { name: 'Submit week for approval' })).toBeVisible()
})

